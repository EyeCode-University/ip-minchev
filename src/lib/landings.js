/*
  Посадочные страницы по направлениям.

  Одностраничник физически не мог ранжироваться сразу по «изготовление
  гидроцилиндров», «арматура высокого давления Ру250» и «токарная обработка
  ЧПУ» — весь вес был сжат в один адрес. Здесь каждое направление получает
  свой URL, заголовок и описание.

  Все факты — параметры, давления, габариты, заводы-заказчики — взяты из
  constants.js, то есть из того же перечня, что показан на главной. Ничего
  придуманного: недостоверный текст на посадочной вредит сильнее, чем её
  отсутствие.

  `imageFiles` — имена файлов из галереи; сопоставление идёт по окончанию src,
  чтобы не дублировать пути.
*/

const byFiles = (files) =>
  files
    .map((file) => GALLERY_IMAGES.find((img) => img.src.endsWith(file)))
    .filter(Boolean);

const capsByNames = (names) =>
  MACHINING_CAPABILITIES.filter((cap) => names.includes(cap.name));

