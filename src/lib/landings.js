export const LANDING_LIST = Object.values(LANDINGS);

// Готовые данные для рендера: картинки и техвозможности уже развёрнуты.
export const getLanding = (slug) => {
  const landing = LANDINGS[slug];
  if (!landing) return null;

  return {
    ...landing,
    images: byFiles(landing.imageFiles),
    capabilities: capsByNames(landing.capabilityNames),
    others: LANDING_LIST.filter((item) => item.slug !== slug),
  };
};
